export function t(
  key: string,
  values?: Record<string, string | number>,
): string {
  const pair = dict[key];
  let text = pair ? pair[getLanguage() === "en" ? 1 : 0] : key;
  if (values) {
    for (const [k, v] of Object.entries(values)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

