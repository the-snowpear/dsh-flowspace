export function tFor(
  locale: Locale,
  key: string,
  values?: Record<string, string | number>,
): string {
  const pair = dict[key];
  let text = pair ? pair[locale === "en" ? 1 : 0] : key;
  if (values) {
    for (const [k, v] of Object.entries(values)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function t(
  key: string,
  values?: Record<string, string | number>,
): string {
  return tFor(getLanguage(), key, values);
}

